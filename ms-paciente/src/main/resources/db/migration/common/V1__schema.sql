-- =====================================================================
-- ms-paciente: fichas de paciente, contatos, condições e medicamentos (requisito 1)
--
-- Cada nutricionista tem a própria ficha de cada paciente. A mesma pessoa atendida por dois
-- nutricionistas tem duas fichas independentes: CPF único POR nutricionista.
-- =====================================================================

CREATE FUNCTION set_atualizado_em() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.atualizado_em := now();
  RETURN NEW;
END $$;

CREATE TABLE paciente (
  id                uuid PRIMARY KEY,
  nutricionista_id  uuid NOT NULL,                           -- tenant (id do nutricionista)
  usuario_id        uuid,                                    -- futuro portal do paciente
  nome              text NOT NULL,
  nome_social       text,
  cpf               varchar(11) CHECK (cpf ~ '^[0-9]{11}$'),  -- opcional (ex.: crianças)
  data_nascimento   date NOT NULL,                           -- idade é sempre calculada
  sexo              varchar(1) NOT NULL CHECK (sexo IN ('F', 'M')),  -- biológico: usado nas equações
  ocupacao          text,
  objetivo          text,
  nivel_atividade   text CHECK (nivel_atividade IN ('SEDENTARIO', 'LEVE', 'MODERADO', 'INTENSO', 'MUITO_INTENSO')),
  observacoes       text,
  status            text NOT NULL DEFAULT 'ATIVO' CHECK (status IN ('ATIVO', 'INATIVO')),
  cep               varchar(8),
  logradouro        text,
  numero            varchar(20),
  complemento       text,
  bairro            text,
  cidade            text,
  uf                varchar(2),
  versao            bigint NOT NULL DEFAULT 0,               -- bloqueio otimista e ordem dos eventos
  criado_em         timestamptz NOT NULL DEFAULT now(),
  atualizado_em     timestamptz NOT NULL DEFAULT now(),
  deletado_em       timestamptz                              -- exclusão lógica
);
CREATE UNIQUE INDEX ux_paciente_cpf_por_nutricionista
  ON paciente (nutricionista_id, cpf) WHERE cpf IS NOT NULL AND deletado_em IS NULL;
CREATE INDEX ix_paciente_nutricionista_nome ON paciente (nutricionista_id, lower(nome)) WHERE deletado_em IS NULL;
CREATE INDEX ix_paciente_usuario ON paciente (usuario_id) WHERE usuario_id IS NOT NULL;
CREATE TRIGGER trg_paciente_atualizado_em BEFORE UPDATE ON paciente
  FOR EACH ROW EXECUTE FUNCTION set_atualizado_em();

CREATE TABLE paciente_contato (
  paciente_id  uuid NOT NULL REFERENCES paciente (id) ON DELETE CASCADE,
  ordem        integer NOT NULL,
  tipo         text NOT NULL CHECK (tipo IN ('CELULAR', 'WHATSAPP', 'TELEFONE', 'EMAIL', 'INSTAGRAM', 'OUTRO')),
  valor        text NOT NULL,
  principal    boolean NOT NULL DEFAULT false,
  observacao   text,                                         -- ex.: "telefone da mãe"
  PRIMARY KEY (paciente_id, ordem)
);

-- Catálogo de condições: tipos fixos + condições do sistema (nutricionista_id nulo) e próprias
CREATE TABLE tipo_condicao (
  id    integer PRIMARY KEY,
  nome  text NOT NULL UNIQUE
);

CREATE TABLE condicao (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo_condicao_id  integer NOT NULL REFERENCES tipo_condicao (id),
  nutricionista_id  uuid,                                    -- NULL = catálogo do sistema
  nome              text NOT NULL,
  descricao         text,
  UNIQUE NULLS NOT DISTINCT (nutricionista_id, nome)
);

CREATE TABLE paciente_condicao (
  id             uuid PRIMARY KEY,
  paciente_id    uuid NOT NULL REFERENCES paciente (id) ON DELETE CASCADE,
  condicao_id    integer NOT NULL REFERENCES condicao (id),
  gravidade      text CHECK (gravidade IN ('LEVE', 'MODERADA', 'GRAVE')),
  desde          date,
  ativa          boolean NOT NULL DEFAULT true,
  observacao     text,
  criado_em      timestamptz NOT NULL DEFAULT now(),
  atualizado_em  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (paciente_id, condicao_id)
);
CREATE TRIGGER trg_paciente_condicao_atualizado_em BEFORE UPDATE ON paciente_condicao
  FOR EACH ROW EXECUTE FUNCTION set_atualizado_em();

CREATE TABLE paciente_medicamento (
  id             uuid PRIMARY KEY,
  paciente_id    uuid NOT NULL REFERENCES paciente (id) ON DELETE CASCADE,
  tipo           text NOT NULL CHECK (tipo IN ('MEDICAMENTO', 'SUPLEMENTO', 'FITOTERAPICO')),
  nome           text NOT NULL,
  dosagem        text,
  frequencia     text,
  inicio         date,
  fim            date,
  observacao     text,
  criado_em      timestamptz NOT NULL DEFAULT now(),
  atualizado_em  timestamptz NOT NULL DEFAULT now(),
  CHECK (fim IS NULL OR inicio IS NULL OR fim >= inicio)
);
CREATE INDEX ix_paciente_medicamento_paciente ON paciente_medicamento (paciente_id);
CREATE TRIGGER trg_paciente_medicamento_atualizado_em BEFORE UPDATE ON paciente_medicamento
  FOR EACH ROW EXECUTE FUNCTION set_atualizado_em();

-- Eventos a publicar no RabbitMQ (core-mensageria)
CREATE TABLE outbox_evento (
  id            uuid PRIMARY KEY,
  routing_key   text NOT NULL,
  agregado_id   uuid NOT NULL,
  tipo          text NOT NULL,
  payload       jsonb NOT NULL,
  criado_em     timestamptz NOT NULL DEFAULT now(),
  publicado_em  timestamptz,
  tentativas    integer NOT NULL DEFAULT 0,
  ultimo_erro   text
);
CREATE INDEX ix_outbox_pendentes ON outbox_evento (criado_em) WHERE publicado_em IS NULL;
