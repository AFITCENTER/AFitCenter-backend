-- =====================================================================
-- ms-planos: catálogo de planos, assinatura de cada nutricionista e faturas
-- =====================================================================

CREATE FUNCTION set_atualizado_em() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.atualizado_em := now();
  RETURN NEW;
END $$;

CREATE TABLE plano (
  id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo               text NOT NULL UNIQUE CHECK (codigo ~ '^[A-Z][A-Z0-9_]{1,39}$'),
  nome                 text NOT NULL,
  descricao            text,
  preco_mensal         numeric(10,2) NOT NULL CHECK (preco_mensal >= 0),     -- 0 = gratuito
  preco_anual          numeric(10,2) CHECK (preco_anual > 0),                -- NULL = sem ciclo anual
  limite_pacientes     integer CHECK (limite_pacientes >= 0),                -- NULL = ilimitado
  limite_consultorios  integer CHECK (limite_consultorios >= 0),
  padrao               boolean NOT NULL DEFAULT false,                       -- plano de quem não assinou
  publico              boolean NOT NULL DEFAULT true,                        -- aparece no catálogo
  ativo                boolean NOT NULL DEFAULT true,                        -- aceita novas assinaturas
  ordem                integer NOT NULL DEFAULT 0,
  versao               bigint NOT NULL DEFAULT 0,
  criado_em            timestamptz NOT NULL DEFAULT now(),
  atualizado_em        timestamptz NOT NULL DEFAULT now(),
  CHECK (preco_mensal > 0 OR preco_anual IS NULL),
  CHECK (NOT padrao OR (preco_mensal = 0 AND ativo))
);
-- Exatamente um plano padrão (o gratuito)
CREATE UNIQUE INDEX ux_plano_padrao ON plano ((true)) WHERE padrao;
CREATE TRIGGER trg_plano_atualizado_em BEFORE UPDATE ON plano
  FOR EACH ROW EXECUTE FUNCTION set_atualizado_em();

-- Uma assinatura por nutricionista (tenant), criada no plano padrão no primeiro acesso
CREATE TABLE assinatura (
  id                 uuid PRIMARY KEY,
  nutricionista_id   uuid NOT NULL UNIQUE,
  plano_id           integer NOT NULL REFERENCES plano (id),
  ciclo              text CHECK (ciclo IN ('MENSAL', 'ANUAL')),                -- NULL no plano gratuito
  forma_pagamento    text CHECK (forma_pagamento IN ('PIX', 'BOLETO', 'CARTAO_CREDITO')),
  status             text NOT NULL DEFAULT 'ATIVA' CHECK (status IN ('ATIVA', 'INADIMPLENTE', 'SUSPENSA')),
  periodo_inicio     timestamptz,                                             -- NULL no gratuito (não vence)
  periodo_fim        timestamptz,
  plano_agendado_id  integer REFERENCES plano (id),                           -- vale no fim do período (cancelamento)
  versao             bigint NOT NULL DEFAULT 0,                               -- bloqueio otimista e ordem dos eventos
  criado_em          timestamptz NOT NULL DEFAULT now(),
  atualizado_em      timestamptz NOT NULL DEFAULT now(),
  CHECK ((periodo_inicio IS NULL) = (periodo_fim IS NULL)),
  CHECK (periodo_fim IS NULL OR periodo_fim > periodo_inicio)
);
CREATE INDEX ix_assinatura_periodo_fim ON assinatura (periodo_fim) WHERE periodo_fim IS NOT NULL;
CREATE TRIGGER trg_assinatura_atualizado_em BEFORE UPDATE ON assinatura
  FOR EACH ROW EXECUTE FUNCTION set_atualizado_em();

-- O que está sendo cobrado. Como é cobrado (Pix, boleto, cartão) fica no ms-pagamentos.
CREATE TABLE fatura (
  id                   uuid PRIMARY KEY,
  assinatura_id        uuid NOT NULL REFERENCES assinatura (id),
  nutricionista_id     uuid NOT NULL,
  tipo                 text NOT NULL CHECK (tipo IN ('MUDANCA_PLANO', 'RENOVACAO')),
  plano_id             integer NOT NULL REFERENCES plano (id),
  ciclo                text NOT NULL CHECK (ciclo IN ('MENSAL', 'ANUAL')),
  valor                numeric(10,2) NOT NULL CHECK (valor > 0),
  forma_pagamento      text NOT NULL CHECK (forma_pagamento IN ('PIX', 'BOLETO', 'CARTAO_CREDITO')),
  vencimento           date NOT NULL,
  periodo_inicio       timestamptz,                                           -- mudança de plano: definido no pagamento
  periodo_fim          timestamptz,
  status               text NOT NULL DEFAULT 'ABERTA' CHECK (status IN ('ABERTA', 'PAGA', 'CANCELADA', 'ESTORNADA')),
  cobranca_id          uuid,                                                  -- cobrança vigente no ms-pagamentos
  tentativas_cobranca  integer NOT NULL DEFAULT 1,                            -- forma a chave de idempotência
  paga_em              timestamptz,
  versao               bigint NOT NULL DEFAULT 0,
  criado_em            timestamptz NOT NULL DEFAULT now(),
  atualizado_em        timestamptz NOT NULL DEFAULT now(),
  CHECK (tipo = 'MUDANCA_PLANO' OR periodo_inicio IS NOT NULL)
);
CREATE INDEX ix_fatura_nutricionista ON fatura (nutricionista_id, criado_em DESC);
CREATE INDEX ix_fatura_assinatura_aberta ON fatura (assinatura_id) WHERE status = 'ABERTA';
CREATE UNIQUE INDEX ux_fatura_cobranca ON fatura (cobranca_id) WHERE cobranca_id IS NOT NULL;
-- No máximo uma mudança de plano em aberto por assinatura
CREATE UNIQUE INDEX ux_fatura_mudanca_aberta ON fatura (assinatura_id) WHERE tipo = 'MUDANCA_PLANO' AND status = 'ABERTA';
-- Uma renovação por período: várias réplicas do agendador não duplicam a fatura
CREATE UNIQUE INDEX ux_fatura_renovacao_periodo ON fatura (assinatura_id, periodo_inicio)
  WHERE tipo = 'RENOVACAO' AND status <> 'CANCELADA';
CREATE TRIGGER trg_fatura_atualizado_em BEFORE UPDATE ON fatura
  FOR EACH ROW EXECUTE FUNCTION set_atualizado_em();

-- Eventos a publicar no RabbitMQ (core-mensageria): assinatura.* e a trilha de auditoria
CREATE TABLE outbox_evento (
  id            uuid PRIMARY KEY,
  routing_key   text NOT NULL,
  agregado_id   uuid NOT NULL,
  tipo          text NOT NULL,
  payload       jsonb NOT NULL,
  criado_em     timestamptz NOT NULL DEFAULT now(),
  publicado_em  timestamptz,
  tentativas    integer NOT NULL DEFAULT 0,
  ultimo_erro   text
);
CREATE INDEX ix_outbox_pendentes ON outbox_evento (criado_em) WHERE publicado_em IS NULL;
